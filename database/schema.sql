-- PostgreSQL 14+; run inside the fintrack database. Non-destructive initialization.
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, token_version INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NULL,
 name VARCHAR(100) NOT NULL, type VARCHAR(32) CHECK (type IN ('income','expense')) NOT NULL,
 owner_key INTEGER GENERATED ALWAYS AS (COALESCE(user_id,0)) STORED,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (owner_key,name,type),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS transactions (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, category_id INTEGER NOT NULL,
 type VARCHAR(32) CHECK (type IN ('income','expense')) NOT NULL, amount DECIMAL(12,2) NOT NULL CHECK (amount > 0),
 description VARCHAR(500) NOT NULL DEFAULT '', transaction_date DATE NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS budgets (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, category_id INTEGER NOT NULL,
 amount DECIMAL(12,2) NOT NULL CHECK (amount > 0), month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
 year SMALLINT NOT NULL CHECK (year BETWEEN 1000 AND 9999),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (user_id,category_id,month,year),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS savings_goals (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, name VARCHAR(100) NOT NULL,
 target_amount DECIMAL(12,2) NOT NULL CHECK (target_amount > 0), target_date DATE NULL, description VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (id,user_id), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS goal_contributions (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, goal_id INTEGER NOT NULL,
 amount DECIMAL(12,2) NOT NULL CHECK (amount > 0), contribution_date DATE NOT NULL, note VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (goal_id,user_id) REFERENCES savings_goals(id,user_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS recurring_payments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, category_id INTEGER NOT NULL,
 name VARCHAR(100) NOT NULL, amount DECIMAL(12,2) NOT NULL CHECK (amount > 0),
 frequency VARCHAR(32) CHECK (frequency IN ('daily','weekly','monthly','yearly')) NOT NULL, next_payment_date DATE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS notifications (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL,
 type VARCHAR(32) CHECK (type IN ('budget_reached','budget_exceeded','recurring_upcoming','goal_achieved')) NOT NULL,
 message VARCHAR(500) NOT NULL, dedupe_key VARCHAR(160) NOT NULL,
 is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (user_id,dedupe_key),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS password_reset_tokens (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, expires_at TIMESTAMPTZ NOT NULL, used_at TIMESTAMPTZ NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS transaction_user_date ON transactions (user_id,transaction_date,id);
CREATE INDEX IF NOT EXISTS transaction_user_category ON transactions (user_id,category_id,type,transaction_date);
CREATE INDEX IF NOT EXISTS contribution_owner_goal_date ON goal_contributions (user_id,goal_id,contribution_date);
CREATE INDEX IF NOT EXISTS recurring_due ON recurring_payments (active,next_payment_date,user_id);
CREATE INDEX IF NOT EXISTS notification_owner_read_date ON notifications (user_id,is_read,created_at);
CREATE INDEX IF NOT EXISTS reset_user_expiry ON password_reset_tokens (user_id,expires_at);

CREATE OR REPLACE FUNCTION fintrack_set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 NEW.updated_at = CURRENT_TIMESTAMP;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER users_updated_at BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION fintrack_set_updated_at();

CREATE OR REPLACE TRIGGER categories_updated_at BEFORE UPDATE ON categories
FOR EACH ROW EXECUTE FUNCTION fintrack_set_updated_at();

CREATE OR REPLACE TRIGGER transactions_updated_at BEFORE UPDATE ON transactions
FOR EACH ROW EXECUTE FUNCTION fintrack_set_updated_at();

CREATE OR REPLACE TRIGGER budgets_updated_at BEFORE UPDATE ON budgets
FOR EACH ROW EXECUTE FUNCTION fintrack_set_updated_at();

CREATE OR REPLACE TRIGGER savings_goals_updated_at BEFORE UPDATE ON savings_goals
FOR EACH ROW EXECUTE FUNCTION fintrack_set_updated_at();

CREATE OR REPLACE TRIGGER recurring_payments_updated_at BEFORE UPDATE ON recurring_payments
FOR EACH ROW EXECUTE FUNCTION fintrack_set_updated_at();
